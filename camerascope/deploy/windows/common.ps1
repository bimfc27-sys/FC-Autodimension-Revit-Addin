# Shared helpers for the CameraScope Windows scripts. Windows PowerShell 5.1+ or PowerShell 7.
$ErrorActionPreference = 'Stop'
$Here = $PSScriptRoot
$EnvFile = Join-Path $Here '.env'
$Compose = @('compose', '-f', (Join-Path $Here 'docker-compose.home.yml'), '--env-file', $EnvFile)

function Write-Step($msg) { Write-Host "==> $msg" -ForegroundColor Cyan }
function Write-Warn($msg) { Write-Host "!!  $msg" -ForegroundColor Yellow }

function Test-Admin {
    $id = [Security.Principal.WindowsIdentity]::GetCurrent()
    (New-Object Security.Principal.WindowsPrincipal $id).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Assert-Command($name, $hint) {
    if (-not (Get-Command $name -ErrorAction SilentlyContinue)) { throw "'$name' was not found. $hint" }
}

function Assert-Docker {
    Assert-Command docker 'Install Docker Desktop (free for personal use): winget install -e --id Docker.DockerDesktop  - then start it and wait until it says "Engine running".'
    & docker info *> $null
    if ($LASTEXITCODE -ne 0) { throw 'Docker Desktop is installed but not running. Start Docker Desktop and run this script again.' }
}

function Get-TailscaleInfo {
    Assert-Command tailscale 'Install Tailscale (free): winget install -e --id Tailscale.Tailscale  - then sign in from the tray icon.'
    $status = (& tailscale status --json) | Out-String | ConvertFrom-Json
    if ($status.BackendState -ne 'Running') { throw "Tailscale is not connected (state: $($status.BackendState)). Sign in from the Tailscale tray icon." }
    $dns = ($status.Self.DNSName).TrimEnd('.')
    $ip = ((& tailscale ip -4) | Select-Object -First 1).Trim()
    if (-not $dns -or -not $ip) { throw 'Could not read this PC''s Tailscale name/IP. Is MagicDNS enabled in the Tailscale admin console (DNS page)?' }
    [pscustomobject]@{ DnsName = $dns; Ip = $ip }
}

function New-Secret([int]$bytes, [switch]$UrlSafe) {
    $b = New-Object byte[] $bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($b); $rng.Dispose()
    $s = [Convert]::ToBase64String($b)
    if ($UrlSafe) { $s = $s.Replace('+', '-').Replace('/', '_').TrimEnd('=') }
    $s
}

function Read-EnvFile {
    $h = [ordered]@{}
    if (Test-Path $EnvFile) {
        foreach ($line in Get-Content $EnvFile) {
            if ($line -match '^\s*([A-Z0-9_]+)=(.*)$') { $h[$Matches[1]] = $Matches[2] }
        }
    }
    $h
}

function Write-EnvFile($h) {
    $lines = @('# CameraScope (Windows home deployment) - generated by install.ps1. Keep this file private and backed up.')
    foreach ($k in $h.Keys) { $lines += "$k=$($h[$k])" }
    # UTF-8 *without* BOM so docker compose reads the first key correctly
    [IO.File]::WriteAllLines($EnvFile, [string[]]$lines, (New-Object Text.UTF8Encoding $false))
    # Restrict the file to the current user
    & icacls $EnvFile /inheritance:r /grant:r "$($env:USERNAME):(R,W)" *> $null
}

function Invoke-Compose([string[]]$args2) {
    & docker @Compose @args2
    if ($LASTEXITCODE -ne 0) { throw "docker compose $($args2 -join ' ') failed" }
}

function Wait-Healthy([int]$seconds = 180) {
    $deadline = (Get-Date).AddSeconds($seconds)
    while ((Get-Date) -lt $deadline) {
        try {
            $r = Invoke-RestMethod -Uri 'http://127.0.0.1:8080/api/health' -TimeoutSec 5
            if ($r.status -eq 'ok') { return $r }
        } catch { }
        Start-Sleep -Seconds 3
    }
    throw 'CameraScope did not become healthy in time. Check: docker compose logs backend'
}
